import re
REVIEW_FIX = [
    ('と正直に書かれている', 'と率直に書かれている'),
    ('変化の程度を正直に書いた投稿がある', '変化の程度を具体的に記した投稿がある'),
    ('慣れるまでの期間を正直に書いている', '慣れるまでの期間を具体的に書いている'),
    ('という正直な書き方の投稿がある', 'という率直な投稿がある'),
    ('英語でのレッスンは無いとの投稿あり', '英語でのレッスンはないとの投稿あり'),
    ('ほぼ無い状態', 'ほぼない状態'),
]
def pre_fix(t):
    for a,b in REVIEW_FIX: t=t.replace(a,b)
    return t
